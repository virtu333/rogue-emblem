def march_notes(text, transpose=0):
    """A note string in the march's own time (2/4, march beats)."""
    tmp = Score('_m', bpm=117, meter=(2, 4))
    p = Part(score=tmp, name='_m', inst='trumpets')
    p.at(1).play(text, transpose=transpose)
    return p.notes


class Clock:
    """The patrol's march beats -> the score's beats. March beat 0 is B's first
    downbeat. Before C the march runs at 3/4 of the army's tempo (117 against
    156); through C it quickens smoothly until its beat is the army's (the
    ratio climbs as 1-(1-u)^2, so it arrives without a jolt); from the hit
    (bar 45) on the two share one grid."""

    def __init__(self, s):
        self.b0 = s.bar(B)
        self.c0 = s.bar(C)
        self.d0 = s.bar(HIT)
        self.L = self.d0 - self.c0
        self.mc = (self.c0 - self.b0) * RATIO
        self.md = self.mc + self.L * (RATIO + (1 - RATIO) * 2 / 3)

    def _f(self, tau):
        u = tau / self.L
        return RATIO * tau + (1 - RATIO) * self.L * (u * u - u ** 3 / 3)

    def t(self, m):
        if m <= self.mc:
            return self.b0 + m / RATIO
        if m >= self.md:
            return self.d0 + (m - self.md)
        lo, hi = 0.0, self.L
        for _ in range(60):
            mid = (lo + hi) / 2
            if self._f(mid) < m - self.mc:
                lo = mid
            else:
                hi = mid
        return self.c0 + (lo + hi) / 2


def put(part, clock, notes, m0, vel, transpose=0):
    for n in notes:
        a = clock(m0 + n.start)
        e = clock(m0 + n.start + n.dur)
        part.note(a, n.pitch + transpose, max(0.05, e - a), vel=min(1.0, vel), art=n.art,
                  staccato=n.staccato, rearticulate=True)


def band_chord(b, t):
    """The band's chord sounding at score beat t: (root, chord), or None."""
    for a, e, root, chord in b.band_chords:
        if a - 1e-6 <= t < e - 1e-6:
            return root, chord
    return None


def waltz_notes(b, t):
    """The army's two notes on a waltz beat under the band (B, C): the band's
    own chord, its lower two notes (F seven: its F and A, not E-flat and F);
    where the band has no chord (its drum tag, its roll-off), the army's D and F."""
    bc = band_chord(b, t)
    if bc is None:
        return ('D4', 'F4')
    notes = bc[1].split()
    return tuple(notes[1:3]) if notes[:2] == ['Eb4', 'F4'] else tuple(notes[:2])


def band_root(b, t, octave):
    bc = band_chord(b, t)
    root = bc[0] if bc else 'D2'
    return root[:-1] + str(octave)


def tuba_note(name):
    """The tuba's oom: the root placed between F2 and E3. Lower, the VSCO
    tuba's fundamental is weak enough that the note is heard a fifth up (its
    third partial), and every B-flat oom read as an F."""
    for octave in (2, 3):
        n = f'{name}{octave}'
        if 41 <= P(n) <= 52:
            return n
    raise ValueError(name)


