def notes(tag=True):
    """[(abs_beat, beats, midi, mora)] in song order. tag=False: round 2's timeline,
    where the vocal-chop drop takes the tag's repeated line (bars 49-52)."""
    from engine.theory import pitch
    out = []
    groups = ((VERSE, 0), (PRE, 0), (CHORUS, 0)) + (((TAG_LINE, TAG_UP),) if tag else ()) \
        + ((OUTRO, 0),)
    for group, up in groups:
        for bar, beat, d, p, m in group:
            out.append(((bar - 1) * 4 + beat, d, pitch(p) + up, m))
    out.sort()
    for a, b in zip(out, out[1:]):
        assert a[0] + a[1] <= b[0] + 1e-9, f'overlap at beat {a[0]} ({a[3]}) -> {b[0]} ({b[3]})'
    return out


def note_string(start_bar=1, tag=True):
    """The melody as one note string from `start_bar` (rests filled in)."""
    from engine.theory import pitch
    names = ['C', 'C#', 'D', 'Eb', 'E', 'F', 'F#', 'G', 'Ab', 'A', 'Bb', 'B']
    cur = (start_bar - 1) * 4
    toks = []
    for t, d, p, _ in notes(tag):
        if t > cur + 1e-9:
            toks.append(f'r:{t - cur:g}')
        toks.append(f'{names[p % 12]}{p // 12 - 1}:{d:g}')
        cur = t + d
    return ' '.join(toks)


